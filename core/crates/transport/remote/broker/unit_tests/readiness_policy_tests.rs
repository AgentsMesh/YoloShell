use super::super::timing::{
    BROKER_CLIENT_OPERATION_TIMEOUT, BROKER_READY_TIMEOUT, CONNECTION_BOOTSTRAP_TIMEOUT,
    EXISTING_SOCKET_CLIENT_OPERATION_TIMEOUT, MANAGEMENT_OPERATION_TIMEOUT, RUNTIME_OPEN_TIMEOUT,
};
use crate::remote::SSH_OPERATION_TIMEOUT;
use std::time::Duration;

#[test]
fn connection_bootstrap_has_a_distinct_larger_budget_than_channel_open() {
    assert!(CONNECTION_BOOTSTRAP_TIMEOUT > SSH_OPERATION_TIMEOUT);
}

#[test]
fn nested_runtime_budgets_have_strict_settlement_margins() {
    assert!(CONNECTION_BOOTSTRAP_TIMEOUT + SSH_OPERATION_TIMEOUT < RUNTIME_OPEN_TIMEOUT);
    assert_eq!(BROKER_READY_TIMEOUT, MANAGEMENT_OPERATION_TIMEOUT);
    assert!(CONNECTION_BOOTSTRAP_TIMEOUT < BROKER_READY_TIMEOUT);
    assert!(BROKER_READY_TIMEOUT < BROKER_CLIENT_OPERATION_TIMEOUT);
    assert!(BROKER_CLIENT_OPERATION_TIMEOUT < RUNTIME_OPEN_TIMEOUT);
    assert!(RUNTIME_OPEN_TIMEOUT < EXISTING_SOCKET_CLIENT_OPERATION_TIMEOUT);
    assert!(
        Duration::from_millis(crate::cli::constants::CATALOG_MAXIMUM_DEADLINE_MILLISECONDS)
            < EXISTING_SOCKET_CLIENT_OPERATION_TIMEOUT
    );
}
