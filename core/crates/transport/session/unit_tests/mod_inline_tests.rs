use super::*;

#[cfg(feature = "yolo-unit-tests")]
#[test]
fn session_startup_deadlines_preserve_durable_settlement_margins() {
    assert_eq!(
        WORKER_READY_TIMEOUT,
        SESSION_DURABLE_STARTUP_IO_BUDGET + SESSION_DURABLE_STARTUP_SETTLEMENT_MARGIN
    );
    assert_eq!(
        SESSION_STARTUP_CLIENT_TIMEOUT,
        WORKER_READY_TIMEOUT + SESSION_STARTUP_RESPONSE_SETTLEMENT_MARGIN
    );
    assert!(SESSION_DURABLE_STARTUP_IO_BUDGET < WORKER_READY_TIMEOUT);
    assert!(WORKER_READY_TIMEOUT < SESSION_STARTUP_CLIENT_TIMEOUT);
    assert_eq!(
        SESSION_RESUME_INNER_BUDGET,
        SESSION_RESUME_LIFECYCLE_LOCK_TIMEOUT
            + WORKER_SHUTDOWN_SETTLEMENT_TIMEOUT
            + WORKER_READY_TIMEOUT
    );
    assert_eq!(
        SESSION_RESUME_CLIENT_TIMEOUT,
        SESSION_RESUME_INNER_BUDGET + SESSION_STARTUP_RESPONSE_SETTLEMENT_MARGIN
    );
    assert!(SESSION_STARTUP_CLIENT_TIMEOUT < SESSION_RESUME_CLIENT_TIMEOUT);
}

#[test]
fn worker_shutdown_budget_covers_ingress_projection_response_and_final_publication() {
    assert_eq!(
        AGENT_HOOK_DRAIN_TIMEOUT,
        AGENT_HOOK_REQUEST_TIMEOUT + AGENT_HOOK_RESPONSE_TIMEOUT + AGENT_HOOK_ABORT_TIMEOUT * 2
    );
    assert_eq!(
        WORKER_SHUTDOWN_SETTLEMENT_TIMEOUT,
        AGENT_HOOK_DRAIN_TIMEOUT * 2
            + WORKER_RESPONSE_DRAIN_TIMEOUT
            + SESSION_DURABLE_STARTUP_SETTLEMENT_MARGIN
    );
    assert!(WORKER_RESPONSE_DRAIN_TIMEOUT < WORKER_READY_TIMEOUT);
    assert!(HOST_DEFERRED_TERMINATION_SETTLEMENT_TIMEOUT < WORKER_SHUTDOWN_SETTLEMENT_TIMEOUT);
}

#[cfg(feature = "yolo-unit-tests")]
#[test]
fn worker_deadlines_cover_every_scheduled_termination_phase() {
    assert_eq!(
        WORKER_TERMINATION_PROTOCOL_TIMEOUT,
        MAXIMUM_SCHEDULED_TERMINATION_DRAIN + PROCESS_SCAN_DEADLINE_OVERRUN_MARGIN
    );
    assert_eq!(
        WORKER_AUTH_TIMEOUT,
        WORKER_TERMINATION_PROTOCOL_TIMEOUT + WORKER_AUTH_RESPONSE_MARGIN
    );
    assert!(MAXIMUM_SCHEDULED_TERMINATION_DRAIN < WORKER_TERMINATION_PROTOCOL_TIMEOUT);
    assert!(WORKER_TERMINATION_PROTOCOL_TIMEOUT < WORKER_AUTH_TIMEOUT);
    assert_eq!(
        HOST_DEFERRED_TERMINATION_SETTLEMENT_TIMEOUT,
        WORKER_TERMINATION_PROTOCOL_TIMEOUT + HOST_PROCESS_EXIT_TIMEOUT
    );
    assert!(WORKER_TERMINATION_PROTOCOL_TIMEOUT < HOST_DEFERRED_TERMINATION_SETTLEMENT_TIMEOUT);
    assert_eq!(
        GUARDIAN_NAMESPACE_LOSS_SETTLEMENT_TIMEOUT,
        HOST_DEFERRED_TERMINATION_SETTLEMENT_TIMEOUT + SESSION_LIFECYCLE_RESPONSE_SETTLEMENT_MARGIN
    );
    assert!(
        HOST_DEFERRED_TERMINATION_SETTLEMENT_TIMEOUT < GUARDIAN_NAMESPACE_LOSS_SETTLEMENT_TIMEOUT
    );
    assert_eq!(
        PTY_CAPABILITY_SETTLEMENT_TIMEOUT,
        FORCE_TERMINATION_TIMEOUT + FORCE_TERMINATION_CONFIRM_TIMEOUT
    );
    assert_eq!(
        PROCESS_CAPABILITY_EXIT_EVENT_CONVERGENCE_TIMEOUT,
        PROCESS_SCAN_DEADLINE_OVERRUN_MARGIN
    );
    assert!(PROCESS_CAPABILITY_EXIT_EVENT_CONVERGENCE_TIMEOUT < PTY_CAPABILITY_SETTLEMENT_TIMEOUT);
}

#[cfg(feature = "yolo-unit-tests")]
#[test]
fn lifecycle_client_deadline_covers_inner_work_and_response_settlement() {
    assert_eq!(
        SESSION_LIFECYCLE_INNER_BUDGET,
        WORKER_AUTH_TIMEOUT
            + WORKER_TERMINATION_PROTOCOL_TIMEOUT
            + HOST_DEFERRED_TERMINATION_SETTLEMENT_TIMEOUT
            + HOST_ARCHIVE_SETTLEMENT_TIMEOUT
            + LINUX_CONTAINMENT_RECOVERY_TIMEOUT
    );
    assert_eq!(
        SESSION_LIFECYCLE_CLIENT_TIMEOUT,
        SESSION_LIFECYCLE_INNER_BUDGET + SESSION_LIFECYCLE_RESPONSE_SETTLEMENT_MARGIN
    );
    assert!(Duration::ZERO < PROCESS_SCAN_DEADLINE_OVERRUN_MARGIN);
    assert!(Duration::ZERO < WORKER_AUTH_RESPONSE_MARGIN);
    assert!(Duration::ZERO < HOST_PROCESS_EXIT_TIMEOUT);
    assert!(Duration::ZERO < HOST_DEFERRED_TERMINATION_SETTLEMENT_TIMEOUT);
    assert!(Duration::ZERO < HOST_ARCHIVE_SETTLEMENT_TIMEOUT);
    assert!(Duration::ZERO < LINUX_CONTAINMENT_RECOVERY_TIMEOUT);
    assert!(Duration::ZERO < SESSION_LIFECYCLE_RESPONSE_SETTLEMENT_MARGIN);
    assert!(SESSION_LIFECYCLE_INNER_BUDGET < SESSION_LIFECYCLE_CLIENT_TIMEOUT);
}
