pub const MAX_OUTBOX_BYTES: usize = crate::paths::MAX_DURABLE_JSON_BYTES as usize;
pub const MAX_PENDING_EVENTS: usize = crate::agent::hooks::MAX_REPLAY_WINDOW;
pub const MAX_ACKNOWLEDGED_EVENTS: usize = crate::agent::hooks::MAX_REPLAY_WINDOW;
pub(crate) const MAX_OCCURRENCE_BINDINGS: usize = crate::agent::hooks::MAX_REPLAY_WINDOW;
pub(crate) const MAX_DURABLE_REJECTIONS: usize = 1;

const NON_ENVELOPE_HEADROOM_DIVISOR: usize = 16;
pub(crate) const NON_ENVELOPE_HEADROOM_BYTES: usize =
    MAX_OUTBOX_BYTES / NON_ENVELOPE_HEADROOM_DIVISOR;
const RECEIPT_HEADROOM_PARTS: usize = 4;
const RECEIPT_HEADROOM_ALLOCATED_PARTS: usize = 3;
pub(crate) const OCCURRENCE_BINDING_BUDGET_BYTES: usize =
    NON_ENVELOPE_HEADROOM_BYTES * RECEIPT_HEADROOM_ALLOCATED_PARTS / RECEIPT_HEADROOM_PARTS;
pub(crate) const STRUCTURAL_HEADROOM_BYTES: usize =
    NON_ENVELOPE_HEADROOM_BYTES - OCCURRENCE_BINDING_BUDGET_BYTES;
pub(crate) const MAX_DURABLE_REJECTION_BYTES: usize =
    STRUCTURAL_HEADROOM_BYTES / MAX_DURABLE_REJECTIONS;

pub(crate) const MAX_OCCURRENCE_BINDING_BYTES: usize =
    OCCURRENCE_BINDING_BUDGET_BYTES / MAX_OCCURRENCE_BINDINGS;
