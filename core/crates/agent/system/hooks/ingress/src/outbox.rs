use super::constants::{
    INVALID, MAX_OUTBOX_EVENTS, MAX_OUTBOX_SCOPES, MAX_PROVIDER_BYTES,
};
use super::contract::{HookRequest, HookScope, SCHEMA_VERSION};
use anyhow::{Context, Result, ensure};
use serde::{Deserialize, Serialize};
use serde_json::Value;
use std::collections::{HashSet, VecDeque};
use std::path::Path;
use uuid::Uuid;

#[path = "outbox_storage.rs"]
mod storage;

#[derive(Default, Deserialize, Serialize)]
#[serde(deny_unknown_fields)]
pub(super) struct Outbox {
    queues: Vec<Queue>,
}

#[derive(Deserialize, Serialize)]
#[serde(deny_unknown_fields)]
struct Queue {
    scope: HookScope,
    acknowledged: u64,
    events: VecDeque<Event>,
}

#[derive(Deserialize, Serialize)]
#[serde(deny_unknown_fields)]
struct Event {
    schema_version: u16,
    provider: String,
    event_sequence: u64,
    #[serde(with = "yolo_crypto::serde_uuid")]
    event_id: Uuid,
    payload: Value,
}

/// Append one provider payload for `scope`. The sequence continues the durable
/// queue; the event id is generated by the caller so a replay stays idempotent.
pub fn enqueue(
    path: &Path,
    scope: HookScope,
    provider: &str,
    event_id: Uuid,
    payload: Value,
) -> Result<u64> {
    ensure!(
        scope.is_valid()
            && !provider.is_empty()
            && provider.len() <= MAX_PROVIDER_BYTES
            && !event_id.is_nil(),
        INVALID
    );
    storage::update(path, |state| {
        state.queues.retain(|queue| {
            queue.scope == scope
                || !queue.events.is_empty()
                || yolo_process::process_identity_relation(
                    queue.scope.agent.pid,
                    queue.scope.agent.start_time,
                ) != yolo_process::ProcessIdentityRelation::Gone
        });
        let index = match state
            .queues
            .iter()
            .position(|queue| queue.scope == scope)
        {
            Some(index) => index,
            None => {
                ensure!(state.queues.len() < MAX_OUTBOX_SCOPES, INVALID);
                state.queues.push(Queue {
                    scope,
                    acknowledged: u64::default(),
                    events: VecDeque::new(),
                });
                state.queues.len() - 1
            }
        };
        let queue = &mut state.queues[index];
        if let Some(existing) = queue
            .events
            .iter()
            .find(|event| event.event_id == event_id)
        {
            ensure!(existing.provider == provider, INVALID);
            return Ok(existing.event_sequence);
        }
        ensure!(queue.events.len() < MAX_OUTBOX_EVENTS, INVALID);
        let sequence = queue
            .events
            .back()
            .map_or(queue.acknowledged, |event| event.event_sequence)
            .checked_add(1)
            .context(INVALID)?;
        queue.events.push_back(Event {
            schema_version: SCHEMA_VERSION,
            provider: provider.to_owned(),
            event_sequence: sequence,
            event_id,
            payload,
        });
        Ok(sequence)
    })
}

/// First unacknowledged request for `scope`.
pub fn next(path: &Path, scope: HookScope) -> Result<Option<HookRequest>> {
    storage::read(path, |state| {
        Ok(state
            .queues
            .iter()
            .find(|queue| queue.scope == scope)
            .and_then(|queue| queue.events.front())
            .map(|event| HookRequest {
                schema_version: event.schema_version,
                provider: event.provider.clone(),
                scope,
                event_sequence: event.event_sequence,
                event_id: event.event_id,
                payload: event.payload.clone(),
            }))
    })
}

pub fn acknowledge(path: &Path, scope: HookScope, sequence: u64) -> Result<()> {
    storage::update(path, |state| {
        let queue = state
            .queues
            .iter_mut()
            .find(|queue| queue.scope == scope)
            .context(INVALID)?;
        if sequence <= queue.acknowledged {
            return Ok(());
        }
        // The client delivers strictly in order, so only the queue head may be
        // acknowledged; a later sequence would silently drop pending payloads.
        ensure!(
            queue
                .events
                .front()
                .is_some_and(|event| event.event_sequence == sequence),
            INVALID
        );
        queue.events.pop_front();
        queue.acknowledged = sequence;
        Ok(())
    })
}

/// Drop queues whose agent is gone and whose events are fully acknowledged.
pub fn prune_dead(path: &Path) -> Result<()> {
    storage::update(path, |state| {
        state.queues.retain(|queue| {
            !queue.events.is_empty()
                || yolo_process::process_identity_relation(
                    queue.scope.agent.pid,
                    queue.scope.agent.start_time,
                ) != yolo_process::ProcessIdentityRelation::Gone
        });
        Ok(())
    })
}

impl Outbox {
    pub(super) fn validate(&self) -> Result<()> {
        ensure!(self.queues.len() <= MAX_OUTBOX_SCOPES, INVALID);
        for (index, queue) in self.queues.iter().enumerate() {
            ensure!(
                queue.scope.is_valid()
                    && !self.queues[..index]
                        .iter()
                        .any(|prior| prior.scope == queue.scope)
                    && queue.events.len() <= MAX_OUTBOX_EVENTS,
                INVALID
            );
            let mut previous = queue.acknowledged;
            let mut ids = HashSet::new();
            for event in &queue.events {
                ensure!(
                    event.schema_version == SCHEMA_VERSION
                        && !event.provider.is_empty()
                        && event.provider.len() <= MAX_PROVIDER_BYTES
                        && previous.checked_add(1) == Some(event.event_sequence)
                        && ids.insert(event.event_id)
                        && !event.event_id.is_nil(),
                    INVALID
                );
                previous = event.event_sequence;
            }
        }
        Ok(())
    }
}
